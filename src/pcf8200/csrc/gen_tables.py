"""Generate pcf8200_tables.h: the chip's quantization tables and frame timing, from
tables.py and protocol.py, and the voice's constants from pcf8200_core.py, so C never
holds a hand copy.

    python pcf8200/csrc/gen_tables.py          rewrite the header
    python pcf8200/csrc/gen_tables.py --check  exit 1 if the header is stale

Plain C89 tables, so BRAISPK's Watcom build can share them.  repr() gives the
shortest decimal that reads back as the same double.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))
from pcf8200 import pcf8200_core as core, pcf8200_native as native, protocol, tables  # noqa: E402

OUT = os.path.join(HERE, "pcf8200_tables.h")


def row(values, width):
    values = list(values) + [0] * (width - len(values))
    return "{" + ", ".join(repr(float(v)) for v in values) + "}"


def grid(name, rows, width):
    body = ",\n    ".join(row(r, width) for r in rows)
    return "static const double %s[%d][%d] = {\n    %s\n};\n" % (name, len(rows), width, body)


def device_params():
    """The initialiser of a pcf8200_params: the chip and the amplifier after it, as a
    front end with no Python needs them."""
    p = native.params(gain=core.HIGHPASS_MAKEUP, knee=core.SOFTKNEE)
    fields = []
    for name, _ in p._fields_:
        value = getattr(p, name)
        fields.append(row(value, len(value)) if hasattr(value, "__len__") else repr(float(value)))
    return "#define PCF8200_DEVICE_PARAMS {%s}\n" % ", ".join(fields)


def text():
    fs = [protocol.FS_TAB[i][1] for i in range(4)]
    return "".join([
        "/* Generated by gen_tables.py: do not edit. */\n",
        "#ifndef PCF8200_TABLES_H\n#define PCF8200_TABLES_H\n\n",
        grid("PCF8200_MALE_F", tables.MALE_F, 32),
        grid("PCF8200_MALE_B", tables.MALE_B, 8),
        grid("PCF8200_FEMALE_F", tables.FEMALE_F, 32),
        grid("PCF8200_FEMALE_B", tables.FEMALE_B, 8),
        "static const double PCF8200_AMPL[16] = %s;\n" % row(tables.AMPL, 16),
        "static const double PCF8200_PI[32] = %s;\n" % row(tables.PI, 32),
        "static const double PCF8200_FS_MS[4] = %s;\n" % row(fs, 4),
        "static const int PCF8200_FD_MULT[4] = {%s};\n"
        % ", ".join(str(v) for v in protocol.FD_MULT),
        "#define PCF8200_PI_NOISE %d\n" % protocol.PI_NOISE,
        "#define PCF8200_PITCH_HZ_PER_UNIT %r\n" % tables.PITCH_HZ_PER_UNIT,
        device_params(),
        "\n#endif\n",
    ])


if __name__ == "__main__":
    if "--check" in sys.argv:
        with open(OUT, encoding="ascii", newline="") as f:
            if f.read().replace("\r\n", "\n") != text():
                sys.exit("pcf8200_tables.h is stale: run gen_tables.py")
    else:
        with open(OUT, "w", encoding="ascii", newline="\n") as f:
            f.write(text())
        print(OUT)
